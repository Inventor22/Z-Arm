"""URDF writer for :class:`zarm_sim.model.RobotModel`.

Link and joint names are unprefixed (ROS convention); material names get a
``zarm_`` prefix so the file can be merged with other robots' descriptions.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from typing import Dict, List, Optional

from .model import Box, Cylinder, Joint, Link, Part, RobotModel
from .xmlfmt import num, to_text, vec

MATERIAL_PREFIX = "zarm_"


def _geometry(parent: ET.Element, part: Part) -> None:
    geometry = ET.SubElement(parent, "geometry")
    shape = part.shape
    if isinstance(shape, Box):
        ET.SubElement(geometry, "box", size=vec(shape.size))
    elif isinstance(shape, Cylinder):
        ET.SubElement(geometry, "cylinder", radius=num(shape.radius), length=num(shape.length))
    else:  # pragma: no cover - the model only builds boxes and cylinders
        raise TypeError(f"unsupported shape {shape!r}")


def _origin(parent: ET.Element, xyz: object) -> None:
    ET.SubElement(parent, "origin", xyz=vec(xyz), rpy="0 0 0")  # type: ignore[arg-type]


def _link(link: Link) -> ET.Element:
    element = ET.Element("link", name=link.name)
    if link.inertial is not None:
        inertial = ET.SubElement(element, "inertial")
        _origin(inertial, link.inertial.com)
        ET.SubElement(inertial, "mass", value=num(link.inertial.mass))
        ixx, ixy, ixz, iyy, iyz, izz = link.inertial.inertia
        ET.SubElement(inertial, "inertia", ixx=num(ixx), ixy=num(ixy), ixz=num(ixz), iyy=num(iyy), iyz=num(iyz),
                      izz=num(izz))
    for part in link.parts:
        visual = ET.SubElement(element, "visual", name=part.name)
        _origin(visual, part.xyz)
        _geometry(visual, part)
        ET.SubElement(visual, "material", name=MATERIAL_PREFIX + part.material)
    for part in link.parts:
        if part.collision:
            collision = ET.SubElement(element, "collision", name=part.name)
            _origin(collision, part.xyz)
            _geometry(collision, part)
    return element


def _joint(joint: Joint) -> ET.Element:
    element = ET.Element("joint", name=joint.name, type=joint.kind)
    _origin(element, joint.xyz)
    ET.SubElement(element, "parent", link=joint.parent)
    ET.SubElement(element, "child", link=joint.child)
    if joint.kind != "fixed":
        ET.SubElement(element, "axis", xyz=vec(joint.axis))
        ET.SubElement(element, "limit", lower=num(joint.lower), upper=num(joint.upper), effort=num(joint.effort),
                      velocity=num(joint.velocity))
    return element


def urdf_text(model: RobotModel) -> str:
    root = ET.Element("robot", name=model.name)
    for material in model.materials:
        element = ET.SubElement(root, "material", name=MATERIAL_PREFIX + material.name)
        ET.SubElement(element, "color", rgba=vec(material.rgba))
    parent_joint: Dict[str, Joint] = {joint.child: joint for joint in model.joints}
    for link in model.links:
        joint: Optional[Joint] = parent_joint.get(link.name)
        if joint is not None:
            root.append(ET.Comment(f" {joint.name}: {_describe(joint)} "))
            root.append(_joint(joint))
        root.append(ET.Comment(f" {link.description} "))
        root.append(_link(link))
    d = model.dimensions
    comments: List[str] = [
        "Generated by `python -m zarm_sim.generate` from zarm-sim/zarm_sim/dimensions.py; do not edit by hand.",
        f"Hitbot Z-Arm 2442 (assumed) with a {num(d.z_stroke_mm)} mm Z stroke. SI units. Primitive shapes; "
        "dimension sources and assumptions are in zarm-sim/README.md.",
        "Joint values: j1_shoulder, j2_elbow and j4_wrist are zarm-sdk's J1, J2 and J4 in radians; "
        "j3_vertical is J3 in metres (0 at the top of travel, negative down).",
    ]
    return to_text(root, comments)


def _describe(joint: Joint) -> str:
    if joint.kind == "fixed":
        return "fixed"
    unit = "m" if joint.kind == "prismatic" else "rad"
    return f"{joint.kind}, zarm-sdk {joint.sdk_field}, {num(joint.lower)} to {num(joint.upper)} {unit}"
